private int[][] captureMarks() {

    int[][] marks = new int[3][2];

    marks[0][0] = Integer.parseInt(txtS1T1.getText().trim());
    marks[0][1] = Integer.parseInt(txtS1T2.getText().trim());

    marks[1][0] = Integer.parseInt(txtS2T1.getText().trim());
    marks[1][1] = Integer.parseInt(txtS2T2.getText().trim());

    marks[2][0] = Integer.parseInt(txtS3T1.getText().trim());
    marks[2][1] = Integer.parseInt(txtS3T2.getText().trim());

    for (int[] student : marks) {
        for (int mark : student) {

            if (mark < 0 || mark > 100) {
                throw new IllegalArgumentException(
                    "Marks must be between 0 and 100.");
            }
        }
    }

    return marks;
}


    
private String createReport(int[][] marks) {

    StudentMarks student = new StudentMarks(marks);

    String output = "STUDENT MARKS REPORT\n";
    output += "****************************\n";

    for (int i = 0; i < marks.length; i++) {
        output += "Student " + (i + 1) + ": "
                + marks[i][0] + ", "
                + marks[i][1] + "\n";
    }

    output += "\nTotal Marks: "
            + student.GetTotalMarks() + "\n";

    output += String.format(
            java.util.Locale.US,
            "Average Mark: %.2f\n",
            student.GetAverageMarks());

    output += "Passing Marks: "
            + student.GetPassCount() + "\n";

    output += "Failing Marks: "
            + student.GetFailCount() + "\n";

    output += "Students Processed: "
            + student.GetStudentsProcessed() + "\n";

    output += "****************************";

    return output;
}


private void saveMarks() {

    try {
        int[][] marks = captureMarks();

        String report = createReport(marks);

        try (java.io.FileWriter writer =
                new java.io.FileWriter("studentmarks.txt")) {

            writer.write(report);
        }

        txtDisplay.setText(report);

        lblStudents.setText(
            "Students Processed: " + marks.length);

        javax.swing.JOptionPane.showMessageDialog(
            this, "Marks saved successfully!");

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter valid whole numbers.");

    } catch (IllegalArgumentException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this, e.getMessage());

    } catch (java.io.IOException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this, "Error saving file: " + e.getMessage());
    }
}


private void loadMarks() {

    try (java.io.BufferedReader reader =
            new java.io.BufferedReader(
                new java.io.FileReader("studentmarks.txt"))) {

        if (!"STUDENT MARKS REPORT".equals(reader.readLine())) {
            throw new java.io.IOException("Invalid marks file.");
        }

        reader.readLine(); // Separator line

        int[][] marks = new int[3][2];

        for (int i = 0; i < 3; i++) {

            String line = reader.readLine();
            String prefix = "Student " + (i + 1) + ": ";

            if (line == null || !line.startsWith(prefix)) {
                throw new java.io.IOException(
                    "Missing student " + (i + 1));
            }

            String data = line.substring(prefix.length());

            String[] values = data.split(",");

            if (values.length != 2) {
                throw new java.io.IOException(
                    "Invalid student marks.");
            }

            try {
                marks[i][0] =
                    Integer.parseInt(values[0].trim());

                marks[i][1] =
                    Integer.parseInt(values[1].trim());

            } catch (NumberFormatException e) {
                throw new java.io.IOException(
                    "Invalid marks in file.", e);
            }

            for (int mark : marks[i]) {
                if (mark < 0 || mark > 100) {
                    throw new java.io.IOException(
                        "Mark outside 0-100 range.");
                }
            }
        }

        txtS1T1.setText(String.valueOf(marks[0][0]));
        txtS1T2.setText(String.valueOf(marks[0][1]));

        txtS2T1.setText(String.valueOf(marks[1][0]));
        txtS2T2.setText(String.valueOf(marks[1][1]));

        txtS3T1.setText(String.valueOf(marks[2][0]));
        txtS3T2.setText(String.valueOf(marks[2][1]));

        txtDisplay.setText(createReport(marks));

        lblStudents.setText(
            "Students Processed: " + marks.length);

        javax.swing.JOptionPane.showMessageDialog(
            this, "Marks loaded successfully!");

    } catch (java.io.IOException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this, "Error loading file: " + e.getMessage());
    }
}

    
    
